"""gen_wpe_settings.py -- generates phwebview/PhWpeSettings.inc.

Bare WebCore::Settings carry the YAML's "WebCore" defaults evaluated for this port; the browser we want to match
is upstream WPE WebKit 2.54.1, i.e. the "WebKit" defaults evaluated for PLATFORM(WPE).  This script evaluates both
(first matching conditional key wins, else "default"; same as GeneratePreferences.rb's templates) and emits a
`settings.setXxx(value);` line for every preference whose two values differ and that has a WebCore::Settings setter.

Setter rule (GeneratePreferences.rb): no `webcoreBinding` -> bound to WebCore::Settings, setter "set" + (webcoreName
or name) with the first letter upcased.  webcoreBinding none/custom/DeprecatedGlobalSettings have no Settings setter
and are listed in the .inc comment instead.  A preference-level `condition:` (ENABLE(x) ...) means the setter only
exists if that feature is built: skipped, listed.  String-typed prefs and non-literal defaults (C++ expressions) are
skipped, listed.

Regenerate:
  python3 recipes/gen_wpe_settings.py [UnifiedWebPreferences.yaml] [out.inc]
The YAML defaults to the one in the unpacked WebKit tree (Source/WTF/Scripts/Preferences/UnifiedWebPreferences.yaml under
$PHOREPOC_BUILD/webkit-symbian-work/x32/wpewebkit-2.54.1). Needs PyYAML.
"""
import os, re, sys
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.environ.get('PHOREPOC_BUILD') or os.path.join(HERE, '..', '..', 'core', 'build')
YAML = sys.argv[1] if len(sys.argv) > 1 else os.path.join(BUILD, 'webkit-symbian-work', 'x32', 'wpewebkit-2.54.1', 'Source', 'WTF', 'Scripts', 'Preferences', 'UnifiedWebPreferences.yaml')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', 'os', 'src', 'webkit', 'phwebview', 'PhWpeSettings.inc')

# ---- macro truth tables (unknown macro = false) ----
WPE = {   # WPE WebKit 2.54.1 on Linux, default cmake options
    'PLATFORM(WPE)', 'OS(LINUX)', 'OS(UNIX)', 'USE(GLIB)', 'USE(SKIA)', 'USE(SOUP)', 'USE(GSTREAMER)', 'USE(GSTREAMER_WEBRTC)',
    'USE(COORDINATED_GRAPHICS)', 'USE(THEME_ADWAITA)',
    'ENABLE(VIDEO)', 'ENABLE(MEDIA_STREAM)', 'ENABLE(WEB_RTC)', 'ENABLE(MEDIA_SOURCE)', 'ENABLE(FULLSCREEN_API)', 'ENABLE(WEB_AUDIO)',
}
# (USE(CURL), USE(CAIRO), PLATFORM(COCOA/GTK/IOS_FAMILY/MAC/...), ENABLE(WEBGPU_BY_DEFAULT), ENABLE(GPU_PROCESS_BY_DEFAULT),
#  ENABLE(ARIA_NOTIFY), ENABLE(MODEL_ELEMENT*) ... are all false for WPE.)
our = set()   # our WebCore: no platform macro true at all

def _eval(expr, truth):
    e = re.sub(r'([A-Z][A-Z0-9_]*)\(\s*([A-Za-z0-9_]+)\s*\)', lambda m: 'True' if m.group(0).replace(' ', '') in truth else 'False', str(expr))
    e = e.replace('&&', ' and ').replace('||', ' or ')
    e = re.sub(r'!(?!=)', ' not ', e)
    return bool(eval(e, {'__builtins__': {}}, {}))

def resolve(group, truth):
    """group = dict of {cond-or-'default': value}; first match in file order wins."""
    for k, v in group.items():
        if k == 'default':
            return v
        if _eval(k, truth):
            return v
    raise ValueError('no default')

def lit(v, typ):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if typ == 'double' and isinstance(v, (int, float)):
        return repr(float(v))
    if typ == 'uint32_t' and isinstance(v, int):
        return str(v) + 'u'
    return None

prefs = yaml.safe_load(open(YAML, encoding='utf-8'))
emit, s_cond, s_binding, s_str, s_expr, s_nocore, same = [], [], [], [], [], [], 0
for name, o in prefs.items():
    dv = o['defaultValue']
    if 'WebKit' not in dv or 'WebCore' not in dv:
        s_nocore.append(name); continue
    wk = resolve(dv['WebKit'], WPE)
    wc = resolve(dv['WebCore'], our)
    if wk == wc:
        same += 1; continue
    typ = o['type']
    note = '%s=%r vs %r' % (name, wk, wc)
    if o.get('webcoreBinding'):
        s_binding.append('%s [%s] WPE=%r ours=%r' % (name, o['webcoreBinding'], wk, wc)); continue
    if o.get('condition'):
        s_cond.append('%s [%s] WPE=%r ours=%r' % (name, o['condition'], wk, wc)); continue
    if typ == 'String':
        s_str.append('%s WPE=%r ours=%r' % (name, wk, wc)); continue
    a, b = lit(wk, typ), lit(wc, typ)
    if a is None or b is None:
        s_expr.append('%s WPE=%r ours=%r' % (name, wk, wc)); continue
    wn = o.get('webcoreName') or name
    setter = 'set' + wn[0].upper() + wn[1:]
    emit.append((name, setter, a, o.get('status', '?'), b))

with open(OUT, 'w', newline='\n') as f:
    w = f.write
    w('// GENERATED by recipes/gen_wpe_settings.py, DO NOT EDIT.\n')
    w('// WebCore::Settings values that make a bare WebCore behave like the WPE WebKit 2.54.1 browser: every preference whose\n')
    w('// UnifiedWebPreferences.yaml "WebKit" default (evaluated for PLATFORM(WPE)/Linux/GLib/Skia) differs from the "WebCore"\n')
    w('// default (evaluated for our platform: no platform macro true) and that has a Settings setter.  Included into phwebtest.cpp\n')
    w('// where `settings` is a WebCore::Settings&.  Regenerate: see the script header.\n')
    w('// %d setters; %d prefs already equal.\n' % (len(emit), same))
    for n, s, a, st, b in emit:
        w('settings.%s(%s); // %s, %s: WebCore default %s\n' % (s, a, n, st, b))
    for title, lst in (('Skipped: pref-level condition: (feature probably not built here)', s_cond),
                       ('Skipped: webcoreBinding none/custom/DeprecatedGlobalSettings (no Settings setter)', s_binding),
                       ('Skipped: String-typed', s_str),
                       ('Skipped: default is a C++ expression, not a literal', s_expr)):
        w('//\n// %s (%d):\n' % (title, len(lst)))
        for x in lst:
            w('//   %s\n' % x)
    w('//\n// No WebKit or no WebCore default group (nothing to compare): %d prefs\n' % len(s_nocore))
print('emitted %d, same %d, cond %d, binding %d, string %d, expr %d, nogroup %d' % (len(emit), same, len(s_cond), len(s_binding), len(s_str), len(s_expr), len(s_nocore)))
